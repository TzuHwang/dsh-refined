import com.mojang.datafixers.DataFixer;
import com.mojang.serialization.Dynamic;
import it.unimi.dsi.fastutil.objects.Object2IntMap;
import net.minecraft.util.datafix.DataFixers;
import net.minecraft.util.datafix.fixes.BlockStateData;
import net.minecraft.util.datafix.fixes.References;

import java.io.IOException;
import java.lang.reflect.Field;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * 把 Millénaire 1.12 的 blocklist.txt 转换为 1.20.1 方块状态。
 *
 * 原版方块使用 Minecraft 自带的 DataFixer（1.12 -> 扁平化 -> 1.20.1）；
 * millenaire: 方块按 mapping 文件转换。
 *
 * 用法: BlocklistConverter <blocklist.txt> <millenaire_mapping.txt> <输出.txt> <未解析报告.txt>
 */
public class BlocklistConverter {

    /** 扁平化后第一个数据版本（1.13 快照 17w47a） */
    private static final int FLATTENED_VERSION = 1451;
    /** 1.20.1 数据版本 */
    private static final int TARGET_VERSION = 3465;

    private static final Map<Integer, Dynamic<?>> OLD_BY_ID = new HashMap<>();
    private static final Map<String, List<Integer>> IDS_BY_OLD_NAME = new HashMap<>();
    private static Dynamic<?>[] NEW_BY_ID;

    private static DataFixer fixer;

    public static void main(String[] args) throws Exception {
        Path input = Path.of(args[0]);
        Path mappingFile = Path.of(args[1]);
        Path output = Path.of(args[2]);
        Path report = Path.of(args[3]);

        net.minecraft.SharedConstants.tryDetectVersion();
        loadLegacyTables();
        fixer = DataFixers.getDataFixer();
        Map<String, String> millMapping = readMapping(mappingFile);

        List<String> out = new ArrayList<>();
        List<String> unresolved = new ArrayList<>();
        out.add("// Generated by tools/blocklist-converter from Millénaire 1.12 blocklist.txt. Do not edit by hand;");
        out.add("// edit millenaire_mapping.txt and re-run the converter instead.");
        out.add("// label;blockstate (1.20.1, empty for special points);secondStep;R/G/B;costItem;costValues;costQuantity");

        for (String raw : Files.readAllLines(input, StandardCharsets.UTF_8)) {
            String line = raw.trim();
            if (line.isEmpty() || line.startsWith("//")) {
                continue;
            }
            String[] p = line.split(";", -1);
            if (p.length != 5 && p.length != 8) {
                unresolved.add("BAD LINE: " + line);
                continue;
            }
            String label = p[0];
            String block = p[1];
            String metaOrProps = p[2];
            String state = "";
            if (!block.isEmpty()) {
                state = convertMapped(millMapping, block, metaOrProps);
                if (state == null && block.startsWith("minecraft:")) {
                    state = convertVanilla(block, metaOrProps);
                }
                if (state == null) {
                    unresolved.add(block + ";" + metaOrProps + "    (" + label + ")");
                    state = "minecraft:air";
                }
            }
            String cost = p.length == 8 ? ";" + p[5] + ";" + p[6] + ";" + p[7] : ";;;";
            out.add(label + ";" + state + ";" + p[3] + ";" + p[4] + cost);
        }

        Files.write(output, out, StandardCharsets.UTF_8);
        Files.write(report, unresolved, StandardCharsets.UTF_8);
        System.out.println("Converted " + (out.size() - 3) + " entries, " + unresolved.size() + " unresolved");
    }

    // ================ 原版方块 ================

    @SuppressWarnings("unchecked")
    private static void loadLegacyTables() throws ReflectiveOperationException {
        Field idByOld = BlockStateData.class.getDeclaredField("ID_BY_OLD");
        idByOld.setAccessible(true);
        Object2IntMap<Dynamic<?>> map = (Object2IntMap<Dynamic<?>>) idByOld.get(null);
        for (Object2IntMap.Entry<Dynamic<?>> e : map.object2IntEntrySet()) {
            int id = e.getIntValue();
            Dynamic<?> old = e.getKey();
            OLD_BY_ID.putIfAbsent(id, old);
            String name = old.get("Name").asString("");
            IDS_BY_OLD_NAME.computeIfAbsent(name, k -> new ArrayList<>()).add(id);
        }
        IDS_BY_OLD_NAME.values().forEach(l -> l.sort(Integer::compare));

        Field mapField = BlockStateData.class.getDeclaredField("MAP");
        mapField.setAccessible(true);
        NEW_BY_ID = (Dynamic<?>[]) mapField.get(null);
    }

    private static String convertVanilla(String name, String metaOrProps) {
        List<Integer> ids = IDS_BY_OLD_NAME.get(name);
        if (ids == null) {
            return null;
        }
        Integer chosen = null;
        if (metaOrProps.matches("\\d+")) {
            int wanted = (ids.get(0) & ~15) | Integer.parseInt(metaOrProps);
            chosen = ids.contains(wanted) ? wanted : ids.get(0);
        } else {
            Map<String, String> wanted = parseProps(metaOrProps);
            for (int id : ids) {
                Map<String, String> props = propsOf(OLD_BY_ID.get(id));
                if (wanted.entrySet().stream().allMatch(w -> !props.containsKey(w.getKey()) || props.get(w.getKey()).equals(w.getValue()))) {
                    chosen = id;
                    break;
                }
            }
        }
        if (chosen == null || NEW_BY_ID[chosen] == null) {
            return null;
        }
        Dynamic<?> flattened = NEW_BY_ID[chosen];
        Dynamic<?> current = fixer.update(References.BLOCK_STATE, flattened, FLATTENED_VERSION, TARGET_VERSION);
        return stateString(current);
    }

    // ================ Millénaire 方块 ================

    /**
     * mapping 行格式（左边是 1.12 方块，右边是 1.20.1 方块）：
     *   name;metaOrProps = ns:block[k=v]   精确匹配某个 meta/属性组合
     *   name = ns:block                    保留全部原属性
     *   name = ns:block[]                  丢弃全部原属性
     *   name = ns:block{a,b>c}             只保留 a 和 b，并把 b 改名为 c（如 half>type）
     */
    private static Map<String, String> readMapping(Path file) throws IOException {
        Map<String, String> m = new LinkedHashMap<>();
        for (String raw : Files.readAllLines(file, StandardCharsets.UTF_8)) {
            String line = raw.trim();
            if (line.isEmpty() || line.startsWith("//")) {
                continue;
            }
            String[] kv = line.split(" = ", 2);
            m.put(kv[0].trim(), kv[1].trim());
        }
        return m;
    }

    private static String convertMapped(Map<String, String> mapping, String name, String metaOrProps) {
        String exact = mapping.get(name + ";" + metaOrProps);
        if (exact != null) {
            return exact;
        }
        String target = mapping.get(name);
        if (target == null) {
            return null;
        }
        if (target.endsWith("[]")) {
            return target.substring(0, target.length() - 2);
        }
        if (target.contains("[")) {
            return target;
        }
        Map<String, String> props = metaOrProps.matches("\\d*") ? new TreeMap<>() : parseProps(metaOrProps);
        int brace = target.indexOf('{');
        if (brace >= 0) {
            String spec = target.substring(brace + 1, target.length() - 1);
            target = target.substring(0, brace);
            Map<String, String> kept = new TreeMap<>();
            for (String rule : spec.split(",")) {
                String[] rename = rule.trim().split(">", 2);
                String value = props.get(rename[0]);
                if (value != null) {
                    kept.put(rename.length == 2 ? rename[1] : rename[0], value);
                }
            }
            props = kept;
        }
        if (props.isEmpty()) {
            return target;
        }
        StringBuilder sb = new StringBuilder(target).append('[');
        props.forEach((k, v) -> sb.append(k).append('=').append(v).append(','));
        sb.setLength(sb.length() - 1);
        return sb.append(']').toString();
    }

    // ================ 工具 ================

    private static Map<String, String> parseProps(String s) {
        Map<String, String> m = new TreeMap<>();
        if (s.isEmpty()) {
            return m;
        }
        for (String kv : s.split(",")) {
            String[] parts = kv.split("=", 2);
            m.put(parts[0].trim(), parts[1].trim());
        }
        return m;
    }

    private static Map<String, String> propsOf(Dynamic<?> d) {
        Map<String, String> m = new TreeMap<>();
        d.get("Properties").asMap(k -> k.asString(""), v -> v.asString(""))
            .forEach(m::put);
        return m;
    }

    private static String stateString(Dynamic<?> d) {
        String name = d.get("Name").asString("minecraft:air");
        Map<String, String> props = propsOf(d);
        if (props.isEmpty()) {
            return name;
        }
        StringBuilder sb = new StringBuilder(name).append('[');
        props.forEach((k, v) -> sb.append(k).append('=').append(v).append(','));
        sb.setLength(sb.length() - 1);
        return sb.append(']').toString();
    }
}
